"""Generate read-only Vulkan feature field metadata from the vendored Khronos registry.
Unknown pNext structures remain explicitly unknown; never infer their byte length.
"""
import hashlib
import pathlib
import xml.etree.ElementTree as ET

root = pathlib.Path(__file__).resolve().parents[2]
registry = root / 'references/Vulkan-Headers/registry/vk.xml'
selected = {
    'VkPhysicalDeviceFeatures',
    *('VkPhysicalDeviceVulkan' + v + 'Features' for v in ('11', '12', '13', '14')),
    *('VkPhysicalDevice' + n + 'Features' + suffix for n, suffix in (
        ('ShaderDemoteToHelperInvocation', 'EXT'), ('DynamicRendering', 'KHR'),
        ('MemoryPriority', 'EXT'), ('PageableDeviceLocalMemory', 'EXT'),
        ('ImageRobustness', 'EXT'), ('BufferDeviceAddress', 'KHR'),
        ('TimelineSemaphore', 'KHR'), ('DescriptorIndexing', 'EXT'),
        ('Synchronization2', 'KHR'), ('Robustness2', 'EXT'))),
}
tree = ET.parse(registry)
types = {t.get('name'): t for t in tree.findall('./types/type') if t.get('name')}
resolved = {}
for name in sorted(selected):
    t = types[name]
    while t.get('alias'):
        t = types[t.get('alias')]
    canonical = t.get('name')
    fields = [m.findtext('name') for m in t.findall('member') if m.findtext('type') == 'VkBool32']
    if not fields:
        raise ValueError('no boolean feature fields: ' + name)
    resolved[canonical] = (t, fields)

lines = ['// Generated by tools/generate_feature_metadata.py; do not hand edit.',
         '// Field names from Khronos vk.xml (Apache-2.0 OR MIT).',
         '// Copyright 2015-2026 The Khronos Group Inc.',
         '// SPDX-License-Identifier: Apache-2.0 OR MIT',
         '// Registry SHA256: ' + hashlib.sha256(registry.read_bytes()).hexdigest(),
         '#pragma once', '#include <cstddef>', '#include <cstring>', '#include <memory>', '#include <vulkan/vulkan.h>',
         'namespace evr::diagnostic {',
         'struct FeatureField { const char *name; size_t offset; };',
         'struct FeatureType { const char *name; const FeatureField *fields; size_t count; };']
for name, (t, fields) in sorted(resolved.items()):
    lines += ['inline constexpr FeatureField fields_' + name + '[] = {']
    lines += ['    {"' + f + '", offsetof(' + name + ', ' + f + ')},' for f in fields]
    lines += ['};']
lines += ['inline FeatureType coreFeatureType() { return {"VkPhysicalDeviceFeatures", fields_VkPhysicalDeviceFeatures, sizeof(fields_VkPhysicalDeviceFeatures)/sizeof(FeatureField)}; }',
          'inline FeatureType featureType(VkStructureType type) { switch (type) {']
for name, (t, fields) in sorted(resolved.items()):
    if name == 'VkPhysicalDeviceFeatures':
        continue
    stype = next(m.get('values') for m in t.findall('member') if m.findtext('name') == 'sType')
    lines += ['case ' + stype + ': return {"' + name + '", fields_' + name + ', sizeof(fields_' + name + ')/sizeof(FeatureField)};']
lines += ['default: return {nullptr, nullptr, 0};', '} }',
          '// Typed storage for the standalone host-device fixture; never writes game objects.',
          'struct FeatureStorage { std::shared_ptr<void> object; FeatureType fields; size_t valuesOffset; };',
          'inline FeatureStorage makeFeatureStorage(const char *name) {',
          'if (!std::strcmp(name, "VkPhysicalDeviceFeatures2")) { auto p = std::make_shared<VkPhysicalDeviceFeatures2>(); p->sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2; return {p, coreFeatureType(), offsetof(VkPhysicalDeviceFeatures2, features)}; }']
for name, (t, fields) in sorted(resolved.items()):
    if name == 'VkPhysicalDeviceFeatures':
        continue
    stype = next(m.get('values') for m in t.findall('member') if m.findtext('name') == 'sType')
    lines += ['if (!std::strcmp(name, "' + name + '")) { auto p = std::make_shared<' + name + '>(); p->sType = ' + stype + '; return {p, featureType(' + stype + '), 0}; }']
lines += ['return {{}, {nullptr, nullptr, 0}, 0};', '}', '} // namespace evr::diagnostic', '']
destination = root / 'vrmod/layer/feature_metadata.hpp'
destination.write_text('\n'.join(lines), encoding='utf8')
print('Generated', len(resolved), 'feature types:', destination)
