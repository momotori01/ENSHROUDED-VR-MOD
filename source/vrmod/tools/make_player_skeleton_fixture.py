#!/usr/bin/env python3
"""Test fixture of the player's skeleton for the body IK unit tests.

Source: docs/analysis/motion_hand_default_globals.json (the 102 default joints of the local character's
hierarchy as read in game, model space, metres). Writes vrmod/tests/player_skeleton_fixture.hpp with the
same global poses and the parents; the test turns them into parent-relative joints.
"""
import argparse, json, pathlib


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=pathlib.Path, default=pathlib.Path('docs/analysis/motion_hand_default_globals.json'))
    p.add_argument('--output', type=pathlib.Path, default=pathlib.Path('vrmod/tests/player_skeleton_fixture.hpp'))
    a = p.parse_args()
    rows = json.loads(a.source.read_text(encoding='utf-8'))
    if len(rows) != 102 or [r['index'] for r in rows] != list(range(102)):
        raise SystemExit('unexpected skeleton source')
    if any(r['parent'] != 65535 and r['parent'] >= r['index'] for r in rows) or any(abs(v - 1) > 1e-4 for r in rows for v in r['scale']):
        raise SystemExit('unexpected hierarchy order or scale')
    f = lambda v: repr(float(v)) + 'f'
    out = ['// Generated by tools/make_player_skeleton_fixture.py from docs/analysis/motion_hand_default_globals.json. Do not edit.',
           '#pragma once', '#include <evr/hand_rig.hpp>', 'namespace evr::fixture {',
           'struct SkeletonRow {uint16_t parent;Quat q;Vec3 p;};',
           'inline const SkeletonRow playerSkeletonGlobals[102]={']
    for r in rows:
        out.append(' {%d,{%s},{%s}},' % (r['parent'], ','.join(f(v) for v in r['q']), ','.join(f(v) for v in r['p'])))
    out += ['};',
            '// Parent-relative rest joints and parents, as the game hands them over.',
            'inline void playerSkeleton(std::vector<hand::Joint>& rest,std::vector<uint16_t>& parents){',
            ' rest.assign(102,{});parents.assign(102,0);',
            ' for(size_t i=0;i<102;i++){const auto& g=playerSkeletonGlobals[i];parents[i]=g.parent;',
            '  const Pose global{normalized(g.q),g.p};',
            '  const auto local=g.parent==UINT16_MAX?global:compose(inverse(Pose{normalized(playerSkeletonGlobals[g.parent].q),playerSkeletonGlobals[g.parent].p}),global);',
            '  rest[i].orientation=local.orientation;rest[i].position=local.position;}',
            '}', '}']
    a.output.write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print(a.output)


if __name__ == '__main__':
    main()
